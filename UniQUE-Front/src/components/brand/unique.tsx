export function UniQUE_Logotype({ className }: { className?: string }) {
  const { resolvedTheme } = useTheme();
  const [currentNode, setCurrentNode] = useState<React.ReactNode>(
    <UniQUE_LogotypeLight />,
  );
  useEffect(() => {
    console.log(resolvedTheme);
    switch (resolvedTheme) {
      case "dark":
        setCurrentNode(<UniQUE_LogotypeLight className={className} />);
        break;
      case "light":
        setCurrentNode(<UniQUE_LogotypeDark className={className} />);
        break;
      default:
        setCurrentNode(<UniQUE_LogotypeDark className={className} />);
        break;
    }
  }, [resolvedTheme, className]);
  return currentNode;
}
